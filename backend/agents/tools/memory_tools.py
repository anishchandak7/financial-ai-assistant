"""Memory tools enabling agents to inspect or refer back to session memories."""

from typing import Optional
from contextvars import ContextVar
from langchain_core.tools import tool
from memory.manager import agent_memory_manager
from observability.logger import get_custom_logger

logger = get_custom_logger(name=__name__)

# ContextVar storing active session_id for tool executions
current_session_id_var: ContextVar[Optional[str]] = ContextVar("current_session_id_var", default=None)

def set_current_session_id(session_id: Optional[str]):
    return current_session_id_var.set(session_id)

def get_current_session_id() -> Optional[str]:
    return current_session_id_var.get()


@tool
def refer_agent_memory(
    agent_name: str,
    topic: Optional[str] = None
) -> str:
    """Retrieve previous facts, calculations, or conclusions generated by another specialist agent during this chat session.

    Args:
        agent_name: Name of the agent to query:
            - 'Stock Analyzer Agent': Deep quantitative indicators, support/resistance levels, RSI, MACD.
            - 'Market Analysis Agent': Macro index status, sector trends, equity research docs.
            - 'Finance Q&A Agent': Document citations, tax/finance explanations.
            - 'Conversational Agent': User background, preferences, and greetings.
        topic: Optional specific topic or stock ticker (e.g. 'NVDA', 'RSI', '401k') to focus the recall.

    Returns:
        Summary of what the target agent recorded in its memory during this session.
    """
    session_id = get_current_session_id()
    if not session_id:
        return "No active session context found to inspect memory."

    try:
        logger.info(f"refer_agent_memory invoked for agent '{agent_name}' on topic '{topic}' in session {session_id[:8]}...")
        data = agent_memory_manager.refer_agent_memory(
            session_id=session_id,
            target_agent=agent_name,
            query=topic
        )

        if not data.get("found"):
            return f"No memory recorded for '{agent_name}' in this session yet."

        output_parts = [f"### Session Memory from {agent_name}:"]
        working_mem = data.get("working_memory", {})
        if working_mem:
            output_parts.append("**Recorded Domain Facts / Indicators:**")
            for k, v in working_mem.items():
                output_parts.append(f"- {k}: {v}")

        recent = data.get("recent_turns", [])
        if recent:
            output_parts.append("\n**Recent Dialogue Turns:**")
            for idx, turn in enumerate(recent, 1):
                output_parts.append(f"Turn {idx}:\n- User Query: {turn['query']}\n- Agent Summary: {turn['response']}")

        return "\n".join(output_parts)

    except Exception as e:
        logger.error(f"Error referring agent memory for '{agent_name}': {e}", exc_info=True)
        return f"Error retrieving memory for {agent_name}: {str(e)}"
